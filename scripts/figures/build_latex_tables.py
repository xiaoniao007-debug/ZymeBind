def tex_esc(s: str) -> str:
    s = str(s)
    # Convert markdown **bold** to \textbf{}
    while "**" in s:
        s = s.replace("**", "\\textbf{", 1).replace("**", "}", 1)
    s = s.replace("\\textbf{", "ZZZBFZZZ").replace("}", "ZZZENDZZZ")
    s = (s.replace("\\", "\\textbackslash{}")
          .replace("&", "\\&")
          .replace("%", "\\%")
          .replace("_", "\\_")
          .replace("#", "\\#")
          .replace("$", "\\$")
          .replace("^", "\\textasciicircum{}")
          .replace("τ*", "$\\tau^*$")
          .replace("τ", "$\\tau$")
          .replace("ρ", "$\\rho$")
          .replace("—", "---")
          .replace("†", "$^{\\dagger}$")
          .replace(">=", "$\\ge$")
          .replace("<=", "$\\le$")
          .replace("<", "$<$")
          .replace(">", "$>$"))
    s = s.replace("ZZZBFZZZ", "\\textbf{").replace("ZZZENDZZZ", "}")
    return s

def read_tsv(name: str):
    with open(TDIR / name, encoding="utf-8") as f:
        rows = list(csv.reader(f, delimiter="\t"))
    return rows[0], rows[1:]

def make_table(tsv_name, label, caption, col_spec, font_cmd="\\scriptsize", use_longtable=False):
    hdr, rows = read_tsv(tsv_name)
    hdr_tex = " & ".join(f"\\textbf{{{tex_esc(h)}}}" for h in hdr) + " \\\\"
    body = [" & ".join(tex_esc(c) for c in r) + " \\\\" for r in rows]
    if use_longtable:
        return (
            f"{{{font_cmd}\n"
            f"\\setlength{{\\tabcolsep}}{{3.5pt}}\n"
            f"\\begin{{longtable}}{{{col_spec}}}\n"
            f"\\caption{{{caption}}}\\label{{{label}}}\\\\\n"
            f"\\toprule\n{hdr_tex}\n\\midrule\n\\endfirsthead\n"
            f"\\toprule\n{hdr_tex}\n\\midrule\n\\endhead\n"
            f"\\midrule\n\\multicolumn{{{len(hdr)}}}{{r}}{{\\textit{{Continued on next page}}}}\\\\\n\\endfoot\n"
            f"\\bottomrule\n\\endlastfoot\n"
            + "\n".join(body) + "\n"
            f"\\end{{longtable}}\n}}\n"
        )
    return (
        f"\\begin{{table}}[htbp]\n\\centering\n{font_cmd}\n"
        f"\\setlength{{\\tabcolsep}}{{3.5pt}}\n"
        f"\\caption{{{caption}}}\n\\label{{{label}}}\n"
        f"\\resizebox{{\\textwidth}}{{!}}{{\\begin{{tabular}}{{{col_spec}}}\n"
        f"\\toprule\n{hdr_tex}\n\\midrule\n"
        + "\n".join(body) + "\n"
        f"\\bottomrule\n\\end{{tabular}}}}\n\\end{{table}}\n"
    )

